// === first check the type. If type if different, they are different.
// if type is same then check the value, if value is same --> true, if value is false --> false

console.log(2 === 2);

console.log(2 === "2");

console.log(1 === 2);
console.log(true === 2);
console.log(false === 2);
console.log(null === undefined);
console.log(0 === "");
console.log([] === "");
